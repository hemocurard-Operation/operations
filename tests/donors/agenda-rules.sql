create function pg_temp.assert(ok boolean,label text) returns void language plpgsql as $$begin if not coalesce(ok,false) then raise exception 'FAIL %',label;end if;raise notice 'PASS %',label;end$$;
-- Synthetic dates and donors; only execute in the disposable database.
reset role;
select pg_temp.assert(public.donor_agenda_date('2026-02-30') is null,'invalid calendar date ignored');
select pg_temp.assert(public.donor_agenda_date('2026-02-03')='2026-02-03'::date,'ISO date parsed without locale ambiguity');
update donors set donor_import_metadata='{"donation_history":[{"date":"2024-02-01"},{"date":"invalid"}]}' where donor_code='D-TEST';
select set_config('test.actor','e2000000-0000-0000-0000-000000000001',false);
set role authenticated;
select pg_temp.assert((select next_donation_date='2024-04-25'::date from vw_donor_next_donation where donor_code='D-TEST'),'12 weeks equal 84 days across leap February');
select pg_temp.assert((select agenda_state='FECHA_ALCANZADA' and invalid_date_count=1 from vw_donor_next_donation where donor_code='D-TEST'),'past date retained and bad source date flagged');
select pg_temp.assert((select count(*)=1 from vw_donor_next_donation),'agenda respects donor branch RLS');
reset role;
insert into donations(donor_id,donation_date,collection_effective,branch_id) values('e3000000-0000-0000-0000-000000000001','2026-10-01',true,'e1000000-0000-0000-0000-000000000001');
set role authenticated;
select pg_temp.assert((select last_donation_date='2026-10-01' and next_donation_date='2026-12-24' and reference_source='REGISTRO_HEMOCURA' from vw_donor_next_donation where donor_code='D-TEST'),'new recorded donation recalculates next date');
reset role;
insert into donations(donor_id,donation_date,collection_effective,branch_id) values('e3000000-0000-0000-0000-000000000001','2026-10-12',false,'e1000000-0000-0000-0000-000000000001');
set role authenticated;
select pg_temp.assert((select last_donation_date='2026-10-01' from vw_donor_next_donation where donor_code='D-TEST'),'ineffective collection is excluded');
reset role;
update donors set donor_import_metadata='{"donation_history":[{"date":"2099-01-01"}]}' where donor_code='D-TEST';
set role authenticated;
select pg_temp.assert((select next_donation_date is null and agenda_state='FECHA_POR_VERIFICAR' from vw_donor_next_donation where donor_code='D-TEST'),'future last donation flagged rather than scheduling from bad history');
reset role;
update donors set donor_import_metadata=null where donor_code='D-TEST';
delete from donations;
set role authenticated;
select pg_temp.assert((select next_donation_date is null and agenda_state='SIN_FECHA' from vw_donor_next_donation where donor_code='D-TEST'),'missing last donation has no invented next date');
select pg_temp.assert((select count(*)=0 from donor_visits where status in ('POR_CONFIRMAR','CONFIRMADA')),'calculated agenda creates no confirmed appointments');
select pg_temp.assert((select status='PENDIENTE' and not effective_donation from donors where donor_code='D-TEST'),'calculated date does not grant clinical eligibility');
reset role;
select pg_temp.assert(not has_table_privilege('anon','public.vw_donor_next_donation','SELECT'),'anonymous agenda access denied');
