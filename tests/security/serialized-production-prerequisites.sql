CREATE OR REPLACE FUNCTION public.emit_operational_alert(p_branch_id uuid, p_category text, p_severity severity_level, p_source_table text, p_source_id uuid, p_title text, p_description text, p_alert_key text, p_payload jsonb DEFAULT '{}'::jsonb, p_target text DEFAULT 'OPERATIONS'::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_alert_id uuid;
begin
  insert into public.alerts(alert_date,branch_id,category,severity,source_table,source_id,title,description,status,alert_key)
  values(now(),p_branch_id,p_category,p_severity,p_source_table,p_source_id,p_title,p_description,'ABIERTA',p_alert_key)
  on conflict do nothing returning id into v_alert_id;
  if v_alert_id is not null then
    insert into public.integration_outbox(event_type,aggregate_type,aggregate_id,payload,target)
    values('ALERT_CREATED','alert',v_alert_id::text,
      jsonb_build_object('alert_id',v_alert_id,'branch_id',p_branch_id,'category',p_category,'severity',p_severity,'title',p_title,'description',p_description)
      || coalesce(p_payload,'{}'::jsonb),p_target);
  end if;
  return v_alert_id;
end $function$
;
REVOKE ALL ON FUNCTION public.emit_operational_alert(uuid,text,public.severity_level,text,uuid,text,text,text,jsonb,text) FROM public,anon,authenticated;

